#!/usr/bin/env bash
# Generate the deploy-time secrets file (gitignored). Idempotent: existing file is kept.
#
# Why a plain gitignored file rather than ansible-vault: the lab has exactly one
# controller (this Mac) and one target, so vault would add a second secret (the vault
# password file, which would itself have to be gitignored) without protecting anything
# extra. In a team setting you would use ansible-vault or an external secret store
# (HashiCorp Vault, AWS Secrets Manager) and inject at run time; the variables stay the same.
set -euo pipefail
cd "$(dirname "$0")/.."
out=ansible/secrets/secrets.yml
if [[ -f "$out" ]]; then
  echo "secrets: $out exists, keeping it"
  exit 0
fi
mkdir -p ansible/secrets
chmod 700 ansible/secrets

# Oracle wants >= 8 chars with upper, lower and a digit. Keep to alphanumerics so the
# value never needs shell or SQL quoting. 20 chars from /dev/urandom ~ 119 bits.
# Read a fixed number of random bytes first, then filter: `tr </dev/urandom | head -c`
# would leave tr writing into a closed pipe once head exits, and under `pipefail` that
# SIGPIPE (exit 141) fails the script.
gen() {
  local p
  while :; do
    p=$(head -c 512 /dev/urandom | LC_ALL=C tr -dc 'A-Za-z0-9')
    p=${p:0:20}
    [[ ${#p} -eq 20 && "$p" =~ [A-Z] && "$p" =~ [a-z] && "$p" =~ [0-9] ]] && { printf '%s' "$p"; return; }
  done
}

umask 077
cat >"$out" <<YAML
---
# Generated by scripts/gen-secrets.sh on $(date -u +%Y-%m-%dT%H:%MZ). Never commit this file.
oracle_sys_password: "$(gen)"
oracle_exporter_password: "$(gen)"
YAML
chmod 600 "$out"
echo "secrets: wrote $out"
